# ---------------------------------------------------------------- shared lists (hubs + homepage)
def team_anchor(path):
    return (path or "").strip("/").rsplit("/", 1)[-1]


def ym_label(ym):
    y, m = str(ym).split("-")[:2]
    return datetime(int(y), int(m), 1).strftime("%B %Y")


def _dated_finals(L):
    rows = []
    for gid, g in L.games.items():
        if gid not in L.paths or not L.is_final(g):
            continue
        dt = parse_dt(g.get("date"))
        if dt:
            rows.append((dt, gid, g))
    rows.sort(key=lambda r: (r[0], r[1]), reverse=True)
    return rows


def _done_events(L):
    """Finished UFC cards: [(dt, event, bouts)]."""
    out = []
    for e in getattr(L, "ev", {}).values():
        bouts = [L.games[b] for b in e.get("bouts") or [] if b in L.games and b in L.paths]
        if not bouts or not all(L.is_final(g) for g in bouts):
            continue
        dt = parse_dt(e.get("date")) or parse_dt(bouts[0].get("date"))
        if dt:
            out.append((dt, e, bouts))
    out.sort(key=lambda r: r[0], reverse=True)
    return out


def _result_months(L):
    seen = []
    if L.lg == "ufc":
        src = (day_et(dt)[:7] for dt, _, _ in _done_events(L))
    else:
        src = (day_et(dt)[:7] for dt, _, _ in _dated_finals(L))
    for ym in src:
        if ym not in seen:
            seen.append(ym)
    return sorted(seen)


def closing_bits(L, g):
    """Closing spread, total and moneyline from the reference book (Hard Rock, then DraftKings, then FanDuel)."""
    blank = ("—", "—", "—")
    if not g.get("_closing") or not pv.has_line(g):
        return blank
    _, b = pv.ref_book(g)
    if not b:
        return blank
    sp = "—"
    if L.kind != "mma" and isnum(b.get("homeSpread")):
        hs = b["homeSpread"]
        if hs < 0:
            sp = f"{(g.get('home') or {}).get('abbr') or ''} {line(hs)}".strip()
        elif hs > 0:
            sp = f"{(g.get('away') or {}).get('abbr') or ''} {line(-hs)}".strip()
        else:
            sp = "PK"
    tot = num(b["total"]) if isnum(b.get("total")) else "—"
    mls = []
    if isnum(b.get("awayML")):
        mls.append(f"{(g.get('away') or {}).get('abbr') or (g.get('away') or {}).get('last') or ''} {am(b['awayML'])}".strip())
    if isnum(b.get("homeML")):
        mls.append(f"{(g.get('home') or {}).get('abbr') or (g.get('home') or {}).get('last') or ''} {am(b['homeML'])}".strip())
    return sp, tot, (" · ".join(mls) if mls else "—")


def _spread_head(L):
    return "Closing puck line" if L.kind == "hockey" else "Closing run line" if L.kind == "baseball" else "Closing spread"


def _game_tables(L, rows):
    """One table per ET date. Returns (html, [(path, label)] in the same order the links are written)."""
    if not rows:
        return "", []
    by, order = {}, []
    for dt, gid, g in rows:
        d = day_et(dt)
        if d not in by:
            order.append(d)
            by[d] = []
        by[d].append((dt, gid, g))
    head = _spread_head(L)
    parts, listed = [], []
    for d in order:
        gs = by[d]
        lab = et(gs[0][0]).strftime("%A, %B ") + str(et(gs[0][0]).day)
        trs = []
        for dt, gid, g in sorted(gs, key=lambda r: (r[0], r[1])):
            sp, tot, ml = closing_bits(L, g)
            listed.append((L.paths[gid], L.matchup(g)))
            trs.append(f'<tr><td><a href="{esc(L.paths[gid])}">{esc(L.matchup(g))}</a></td><td>{esc(L.score_line(g))}</td>'
                       f'<td class="num">{esc(sp)}</td><td class="num">{esc(tot)}</td><td class="num">{esc(ml)}</td></tr>')
        parts.append(f'<h3 class="sx-seg">{esc(lab)}</h3><div class="card"><div class="tbl-wrap"><table class="books sx-res">'
                     f'<thead><tr><th>Matchup</th><th>Final</th><th>{esc(head)}</th><th>Closing total</th><th>Closing ML</th></tr></thead>'
                     f'<tbody>{"".join(trs)}</tbody></table></div></div>')
    return "".join(parts), listed


def _event_table(L, events):
    if not events:
        return "", []
    listed, trs = [], []
    for dt, e, bouts in events:
        main = min(bouts, key=lambda g: (0 if g.get("mainEvent") else 1, g.get("matchNo") or 99))
        listed.append((e["path"], e["name"]))
        trs.append(f'<tr><td><a href="{esc(e["path"])}">{esc(e["name"])}</a></td>'
                   f'<td>{esc(fmt_et(dt, False))}</td><td>{esc(L.matchup(main))}</td><td>{esc(L.score_line(main))}</td></tr>')
    html = ('<div class="card"><div class="tbl-wrap"><table class="books sx-res"><thead><tr><th>Event</th><th>Date</th><th>Main event</th><th>Result</th></tr></thead>'
            f'<tbody>{"".join(trs)}</tbody></table></div></div>')
    return html, listed


def _team_sections(L):
    """Full season for each team / fighter, newest first. Anchor matches the team page's Full results link."""
    by = {}
    for dt, gid, g in _dated_finals(L):
        for side in ("home", "away"):
            tid = str((g.get(side) or {}).get("id") or "")
            if tid and tid in L.team_paths:
                by.setdefault(tid, []).append((dt, gid, g))
    parts, listed = [], []
    who = "fighter" if L.lg == "ufc" else "team"
    for tid, rows in sorted(by.items(), key=lambda kv: tname(L.team_info.get(kv[0]) or {}).lower()):
        anchor = team_anchor(L.team_paths[tid])
        name = tname(L.team_info.get(tid) or {})
        items = []
        for dt, gid, g in rows:
            me = g["home"] if str(g["home"].get("id")) == tid else g["away"]
            opp = g["away"] if me is g["home"] else g["home"]
            if L.lg == "ufc":
                mark = "W" if me.get("winner") else "L" if opp.get("winner") else "—"
                word = "vs. "
            else:
                mark = "W" if (me.get("score") or 0) > (opp.get("score") or 0) else "L" if (me.get("score") or 0) < (opp.get("score") or 0) else "T"
                word = "vs " if str(g["home"].get("id")) == tid else "at "
            items.append((L.paths[gid], f"{mark} {word}{tname(opp)}", short_day(dt, False)))
            listed.append((L.paths[gid], f"{name} {mark} {word}{tname(opp)}"))
        parts.append(f'<section class="sx-teamsec" id="{esc(anchor)}"><h2>{L.team_link(L.team_info.get(tid) or {"name": name, "id": tid})}</h2>'
                     f'{link_list(items, "pv-list sx-results")}</section>')
    inner = "".join(parts)
    html = section("by-team", f"Full season by {who}", inner) if inner else ""
    return html, listed


