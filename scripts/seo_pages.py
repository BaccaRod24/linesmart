# ---------------------------------------------------------------- archive
class Archive:
    """games-<lg>.json {id: game} (compact, with "closing" lines), players-<lg>.json {pid: snapshot}, state.json
    {"paths": {lg: {id: [path, old...]}}, "slugs": {lg: {pid: slug}}, "lastmod": {path: [hash, iso]}}."""

    def __init__(self, d: Path | None):
        self.dir = Path(d) if d else None
        self.games, self.players, self._orig = {}, {}, {}
        self.state = {"paths": {}, "slugs": {}, "lastmod": {}}
        if not self.dir:
            return
        for lg in ORDER:
            self.games[lg] = self._load(f"games-{lg}.json", {})
            self.players[lg] = self._load(f"players-{lg}.json", {})
        self.state.update(self._load("state.json", {}))

    def _load(self, name, default):
        v = load_json(self.dir / name)
        self._orig[name] = json.dumps(v, sort_keys=True, separators=(",", ":")) if v is not None else None
        return v if isinstance(v, dict) else default

    def save(self):
        if not self.dir:
            return []
        self.dir.mkdir(parents=True, exist_ok=True)
        files = {f"games-{lg}.json": self.games.get(lg, {}) for lg in ORDER}
        files.update({f"players-{lg}.json": self.players.get(lg, {}) for lg in ORDER})
        files["state.json"] = self.state
        wrote = []
        for name, v in files.items():
            s = json.dumps(v, sort_keys=True, separators=(",", ":"))
            if s != self._orig.get(name):     # only touch files that changed (keeps data-history commits small)
                tmp = self.dir / (name + ".tmp")
                tmp.write_text(s)
                tmp.replace(self.dir / name)
                wrote.append(name)
        return wrote


GAME_KEYS = ["id", "date", "name", "state", "statusDetail", "completed", "venue", "city", "venueState", "venueCountry", "neutral",
             "broadcasts", "note", "event", "segment", "segmentName", "matchNo", "weightClass", "rounds", "mainEvent", "title", "result", "weather"]
SIDE_KEYS = ["id", "abbr", "name", "short", "last", "logo", "color", "record", "score", "winner", "form", "rank", "country"]


def score_num(v):
    """ESPN sends scores as strings ("24"); pages and grading want numbers."""
    if isnum(v):
        return int(v) if float(v).is_integer() else v
    try:
        f = float(str(v).strip())
    except (TypeError, ValueError):
        return None
    return int(f) if f.is_integer() else f


def norm_scores(g):
    """Copy of g with numeric side scores (no-op when absent)."""
    out = dict(g)
    for s in ("home", "away"):
        if isinstance(g.get(s), dict) and g[s].get("score") not in (None, ""):
            out[s] = dict(g[s], score=score_num(g[s]["score"]))
    return out


def compact(g):
    g = norm_scores(g)
    r = {k: g[k] for k in GAME_KEYS if g.get(k) not in (None, "", [], {})}
    for s in ("home", "away"):
        r[s] = {k: (g.get(s) or {}).get(k) for k in SIDE_KEYS if (g.get(s) or {}).get(k) not in (None, "")}
    if isinstance(r.get("weather"), dict):
        r["weather"] = {k: v for k, v in r["weather"].items() if k != "hours"}
    m = g.get("move") or {}
    if m:
        r["move"] = {k: m[k] for k in ("book", "since", "points", "spread", "total", "homeML", "awayML", "notable", "spark") if k in m}
    return r


def closing_of(g):
    books = {k: {x: y for x, y in b.items() if x not in ("source", "openSource")} for k, b in pv.live_books(g).items()}
    o = g.get("odds") or {}
    odds = {k: v for k, v in o.items() if k in ("provider", "homeML", "awayML", "homeSpread", "awaySpread", "total", "overOdds", "underOdds", "homeSpreadOdds", "awaySpreadOdds", "details")} if o else None
    return {"books": books, "odds": odds} if (books or (odds and any(isnum(odds.get(k)) for k in ("homeML", "homeSpread", "total")))) else None


def merge_archive(arch: Archive, lg, games, teams, now):
    """Fold the current window into the archive; fill finals for games that left the window; prune old ones."""
    if not arch.dir:
        return
    A = arch.games.setdefault(lg, {})
    for g in games:
        dt = parse_dt(g.get("date"))
        if not dt or not g.get("id") or not g.get("home") or not g.get("away"):
            continue
        if g.get("state") == "pre" and dt > now + timedelta(hours=ARCHIVE_AHEAD_H):
            continue
        old = A.get(str(g["id"])) or {}
        rec = compact(g)
        cl = closing_of(g) if g.get("state") == "pre" else None
        rec["closing"] = cl or old.get("closing")
        if not rec["closing"]:
            rec.pop("closing")
        if g.get("state") != "pre" and old.get("move") and not g.get("move"):
            rec["move"] = old["move"]
        A[str(g["id"])] = rec
    # finals for games that dropped out of the window before ESPN marked them final, from the teams' recent results
    for gid, rec in A.items():
        if rec.get("state") == "post" or lg == "ufc":
            continue
        dt = parse_dt(rec.get("date"))
        if not dt or dt > now - timedelta(hours=3):
            continue
        h, a = rec.get("home") or {}, rec.get("away") or {}
        for r in ((teams.get(str(h.get("id"))) or {}).get("recent") or []):
            rd = parse_dt(r.get("date"))
            if rd and abs((rd - dt).total_seconds()) < 36 * 3600 and r.get("opp") == a.get("abbr") and r.get("home") and isnum(r.get("pf")):
                pf, pa = score_num(r["pf"]), score_num(r["pa"])
                if pa is None:
                    continue
                h["score"], a["score"] = pf, pa
                h["winner"], a["winner"] = pf > pa, pa > pf
                rec.update(state="post", statusDetail="Final", completed=True)
                break
    cut = now - timedelta(days=KEEP_DAYS)
    for gid in [k for k, v in A.items() if (parse_dt(v.get("date")) or now) < cut]:
        del A[gid]
        (arch.state.get("paths", {}).get(lg) or {}).pop(gid, None)


# ---------------------------------------------------------------- props helpers (port of assets/props-core.js)
def grade(v, ln):
    if not isnum(v) or not isnum(ln):
        return None
    return "o" if v > ln else "u" if v < ln else "p"


def strip(log, mk, ln, n=5):
    out = []
    for d, opp, ha, vals in (log or [])[:n]:
        v = vals.get(mk) if isinstance(vals, dict) and isnum(vals.get(mk)) else None
        out.append({"d": d, "opp": opp, "ha": ha, "v": v, "r": "x" if v is None else grade(v, ln)})
    return out


def rate(log, mk, ln, n=5):
    s = strip(log, mk, ln, n)
    pl = [b for b in s if b["r"] != "x"]
    return {"o": sum(b["r"] == "o" for b in pl), "n": len(pl)}


def is_hot(log, mk, ln):
    r = rate(log, mk, ln, 5)
    return r["n"] >= 2 and r["o"] >= math.ceil(0.8 * r["n"] - 1e-9)


def strip_html(log, mk, ln, n=5):
    """Last-n boxes oldest -> newest, left to right (newest on the right, tagged "latest"). strip() stays latest first for the stats."""
    boxes = []
    s = strip(log, mk, ln, n)[::-1]
    for i, b in enumerate(s):
        word = {"o": "over", "u": "under", "p": "push", "x": "no game"}[b["r"]]
        val = "—" if b["v"] is None else ("✓" if mk == "anytime_td" and b["v"] > 0 else "✗" if mk == "anytime_td" else num(b["v"]))
        last = i == len(s) - 1
        boxes.append(f'<span class="pp-b pp-{b["r"]}" role="listitem" title="{esc(b["d"])} {esc(b["ha"])} {esc(b["opp"])}: {esc(word)}{" (latest)" if last else ""}"><b>{esc(val)}</b><i>{esc(b["opp"])}</i></span>')
    return f'<div class="pp-strip pp-l5" role="list" aria-label="Last {n} games against this line, oldest to newest">{"".join(boxes)}</div>'


def line_text(mk, ln):
    return "Scores a TD" if mk == "anytime_td" else f"O/U {num(ln)}"


# ---------------------------------------------------------------- page shell (from site/index.html)
class Shell:
    def __init__(self, index_html: str, base_url: str):
        t = index_html
        t = re.sub(re.escape(HOME_START) + r".*?" + re.escape(HOME_END), "", t, flags=re.S)
        t = re.sub(r'<section class="intro wrap" id="intro".*?</section>\s*', "", t, flags=re.S)
        t = re.sub(r'<script type="application/ld\+json"[^>]*>.*?</script>\s*', "", t, flags=re.S)
        t = re.sub(r'<noscript><style>#app \.loading.*?</noscript>\s*', "", t, count=1, flags=re.S)
        t = re.sub(r'<main class="wrap" id="app">.*?</main>', "\x00MAIN\x00", t, count=1, flags=re.S)
        t = t.replace("<body class=\"app\">", "\x00BODY\x00", 1)
        t = re.sub(r'(<script src="assets/app\.js[^"]*"></script>)', r'<script src="assets/preview.js"></script>\n\1', t, count=1)
        if "\x00MAIN\x00" not in t or "\x00BODY\x00" not in t:
            raise SystemExit("seo_pages: site/index.html changed shape (main#app / body.app not found)")
        self.t, self.base_url = t, base_url

    def page(self, path, title, desc, main, more="", kind="page", lg="", route="", ld=None, og_type="article", robots=None):
        url = self.base_url + path
        depth = path.count("/")
        t = self.t
        t = t.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="' + ("../" * depth or "./") + '">', 1)
        sub = [
            (r"<title>.*?</title>", f"<title>{esc(title)}</title>"),
            (r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{esc(desc)}">'),
            (r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{esc(url)}">'),
            (r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="{esc(title)}">'),
            (r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{esc(desc)}">'),
            (r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{esc(url)}">'),
            (r'<meta property="og:type" content="[^"]*">', f'<meta property="og:type" content="{og_type}">'),
            (r'<meta name="twitter:title" content="[^"]*">', f'<meta name="twitter:title" content="{esc(title)}">'),
            (r'<meta name="twitter:description" content="[^"]*">', f'<meta name="twitter:description" content="{esc(desc)}">'),
        ]
        for pat, rep in sub:
            t = re.sub(pat, lambda _m, r=rep: r, t, count=1, flags=re.S)
        extra = ""
        if robots:
            extra += f'<meta name="robots" content="{robots}">\n'
        for obj in (ld or []):
            extra += '<script type="application/ld+json">' + json.dumps(obj, separators=(",", ":")).replace("</", "<\\/") + "</script>\n"
        t = t.replace("</head>", extra + "</head>", 1)
        attrs = f'class="app seo-page" data-page="{kind}"' + (f' data-lg="{lg}"' if lg else "") + (f' data-route="{esc(route)}"' if route else "")
        t = t.replace("\x00BODY\x00", f"<body {attrs}>\n<!-- generated by scripts/seo_pages.py from site/data: edit the generator, not this file -->", 1)
        main_html = f'<main class="wrap" id="app">\n{main}\n</main>' + (f'\n<section class="wrap seo-more" aria-label="More on LineSmart">\n{more}\n</section>' if more else "")
        return t.replace("\x00MAIN\x00", main_html, 1)


def crumbs(*items):
    out = ['<a href="./">LineSmart</a>']
    for href, label in items:
        out.append(f'<a href="{esc(href)}">{esc(label)}</a>' if href else esc(label))
    return f'<nav class="pv-crumbs" aria-label="Breadcrumb">{" › ".join(out)}</nav>'


def crumbs_ld(base_url, items):
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": n, "item": base_url + p} for i, (p, n) in enumerate([("", "LineSmart")] + items)]}


def stamp(s):
    """Volatile text (build times) is wrapped so it doesn't change a page's lastmod."""
    return f"<!--v-->{s}<!--/v-->"


def content_hash(html):
    core = re.sub(r"<!--v-->.*?<!--/v-->", "", html, flags=re.S)
    m = re.search(r'<main class="wrap" id="app">.*', core, flags=re.S)
    return hashlib.sha1((m.group(0) if m else core).encode()).hexdigest()[:16]


def section(sid, title, inner):
    return f'<section aria-labelledby="{sid}" id="{sid}-s"><h2 class="section-title" id="{sid}">{title}</h2>{inner}</section>' if inner else ""


def link_list(items, cls="pv-list pv-more"):
    """items: [(href, label, note)]"""
    if not items:
        return ""
    return f'<ul class="{cls}">' + "".join(f'<li><a href="{esc(h)}">{esc(t)}</a>' + (f' <span class="na">{esc(w)}</span>' if w else "") + "</li>" for h, t, w in items) + "</ul>"


# ---------------------------------------------------------------- per-league context
class League:
    def __init__(self, lg, ix, props, arch: Archive, now, base_url):
        self.lg, self.now, self.base_url = lg, now, base_url
        self.league = dict(ix.get("league") or {})
        self.kind = self.league.get("kind") or ("mma" if lg == "ufc" else "football")
        self.name = NAMES[lg]
        self.full = self.league.get("full") or self.name
        self.generated = parse_dt(ix.get("generated")) or now
        self.teams = ix.get("teams") or {}
        self.events = {str(e["id"]): e for e in (ix.get("events") or []) if e.get("id")}
        self.props = props or {}
        self.markets = self.props.get("markets") or {}
        self.cur = {str(g["id"]): norm_scores(g) for g in (ix.get("games") or []) if g.get("id") and g.get("home") and g.get("away")}
        self.arch = arch
        self.games = {}      # id -> game used for the page (current copy, or archived copy with closing lines)
        self.current = set() # ids still in the data window (pages hydrate with the live app view)
        self.paths = {}      # id -> path
        self.old_paths = {}  # id -> [older paths to redirect]
        self.players = {}    # pid -> {"p": player, "rows": [(gid, row)], "path": ..., "archived": bool, "seen": iso}
        self.team_paths = {} # team id -> path
        self.team_info = {}  # team id -> side dict (name/abbr/logo/...)
        self.event_paths = {}
        self.hub = f"{lg}/"

    def is_final(self, g):
        return g.get("state") == "post" or bool(g.get("completed"))

    def score_known(self, g):
        if self.lg == "ufc":
            return bool(g.get("result")) or any((g.get(s) or {}).get("winner") for s in ("home", "away"))
        return isnum((g.get("home") or {}).get("score")) and isnum((g.get("away") or {}).get("score"))

    def select(self):
        cfg, now = LEAGUES[self.lg], self.now
        arch_games = (self.arch.games.get(self.lg) or {}) if self.arch.dir else {}
        horizon = now + timedelta(days=cfg["days"])
        for gid, g in self.cur.items():
            dt = parse_dt(g.get("date"))
            if not dt:
                continue
            ar = arch_games.get(gid) or {}
            st = g.get("state")
            if st == "pre":
                if dt > horizon or (cfg["odds"] and not pv.has_line(g)) or dt < now - timedelta(hours=12):
                    continue
                # pro leagues: games without a line yet still get a page when they're close (records, form, injuries)
                if not pv.has_line(g) and dt > now + timedelta(hours=72):
                    continue
                self.games[gid] = g
            elif st == "in":
                self.games[gid] = dict(g, **(ar.get("closing") or {})) if ar.get("closing") and not pv.has_line(g) else g
            else:
                if not self.score_known(g):
                    continue
                gg = dict(g)
                cl = ar.get("closing")
                if cl:
                    gg.update(books=cl.get("books") or {}, odds=cl.get("odds"), _closing=True)
                elif pv.has_line(g):
                    gg["_closing"] = True
                if cfg["pastOdds"] and not pv.has_line(gg):
                    continue
                if ar.get("move") and not gg.get("move"):
                    gg["move"] = ar["move"]
                self.games[gid] = gg
            self.current.add(gid)
        for gid, rec in arch_games.items():
            rec = norm_scores(rec)
            if gid in self.cur or not self.is_final(rec) or not self.score_known(rec):
                continue
            dt = parse_dt(rec.get("date"))
            if not dt or dt < now - timedelta(days=KEEP_DAYS):
                continue
            gg = dict(rec)
            cl = rec.get("closing") or {}
            gg.update(books=cl.get("books") or {}, odds=cl.get("odds"), _closing=bool(cl), _archived=True)
            if cfg["pastOdds"] and not pv.has_line(gg):
                continue
            self.games[gid] = gg

    def assign_paths(self):
        stored = self.arch.state.setdefault("paths", {}).setdefault(self.lg, {}) if self.arch.dir else {}
        used = set()
        # keep paths we already published; new games get one in date order
        order = sorted(self.games.values(), key=lambda g: (g.get("date") or "", str(g["id"])))
        for g in order:
            gid = str(g["id"])
            prev = stored.get(gid) or []
            want = self.game_slug(g)
            if prev and (g.get("state") != "pre" or prev[0].rsplit("/", 2)[-2].startswith(want)):
                path = prev[0]
            else:
                base = want
                path = self._gpath(base)
                if path in used:
                    path = self._gpath(f"{base}-{gid}")
            used.add(path)
            self.paths[gid] = path
            olds = [p for p in prev if p != path]
            if olds:
                self.old_paths[gid] = olds
            if self.arch.dir:
                stored[gid] = [path] + olds[:3]

    def _gpath(self, slug):
        return f"{self.lg}/{'fights' if self.lg == 'ufc' else 'games'}/{slug}/"

    def game_slug(self, g):
        d = day_et(parse_dt(g["date"]))
        a, h = g.get("away") or {}, g.get("home") or {}
        sep = "vs" if self.lg == "ufc" else "at"
        return f"{slugify(a.get('name') or a.get('abbr'))}-{sep}-{slugify(h.get('name') or h.get('abbr'))}-{d}"

    # players (props) ------------------------------------------------------
    def collect_players(self):
        if self.lg == "ufc":
            return
        P = self.props.get("players") or {}
        slugs = self.arch.state.setdefault("slugs", {}).setdefault(self.lg, {}) if self.arch.dir else {}
        for gid, gp in (self.props.get("games") or {}).items():
            gid = str(gid)
            g = self.cur.get(gid)
            if not g or g.get("state") == "post" or gid not in self.paths:
                continue
            for r in gp.get("props") or []:
                pid = str(r[0])
                if pid not in P:
                    continue
                e = self.players.setdefault(pid, {"p": P[pid], "rows": [], "archived": False, "seen": iso(self.now)})
                e["rows"].append((gid, r))
        ap = self.arch.players.setdefault(self.lg, {}) if self.arch.dir else {}
        for pid, e in self.players.items():
            if self.arch.dir:
                ap[pid] = {"p": e["p"], "rows": e["rows"], "seen": e["seen"]}
        cut = self.now - timedelta(days=PLAYER_KEEP_DAYS)
        for pid in list(ap):
            if (parse_dt(ap[pid].get("seen")) or self.now) < cut:
                del ap[pid]
                continue
            if pid not in self.players:
                e = dict(ap[pid], archived=True)
                e["rows"] = [tuple(x) for x in e.get("rows") or []]
                self.players[pid] = e
        used = {}
        for pid in sorted(self.players, key=lambda k: (self.players[k]["archived"], self.players[k]["p"].get("n") or "", k)):
            base = slugs.get(pid) or slugify(self.players[pid]["p"].get("n") or pid)
            if base in used and used[base] != pid:
                base = f"{base}-{slugify(self.players[pid]['p'].get('ta') or pid)}"
                if base in used:
                    base = f"{base}-{pid}"
            used[base] = pid
            if self.arch.dir:
                slugs[pid] = base
            self.players[pid]["path"] = f"{self.lg}/props/{base}/"

    def collect_teams(self):
        used = {}
        for gid, g in sorted(self.games.items(), key=lambda kv: kv[1].get("date") or "", reverse=True):
            for s in ("home", "away"):
                t = g.get(s) or {}
                tid = str(t.get("id") or "")
                if not tid or tid in self.team_info:
                    continue
                self.team_info[tid] = t
        for tid, t in sorted(self.team_info.items(), key=lambda kv: (kv[1].get("name") or "", kv[0])):
            base = slugify(t.get("name") or t.get("abbr") or tid)
            if base in used:
                base = f"{base}-{tid}"
            used[base] = tid
            self.team_paths[tid] = f"{self.lg}/{'fighters' if self.lg == 'ufc' else 'teams'}/{base}/"

    def collect_events(self):
        if self.lg != "ufc":
            return
        evs = {}
        for gid, g in self.games.items():
            ev = g.get("event") or {}
            if ev.get("id"):
                e = evs.setdefault(str(ev["id"]), {"id": str(ev["id"]), "name": ev.get("name") or "UFC", "bouts": [], "date": g.get("date")})
                e["bouts"].append(gid)
                full = self.events.get(str(ev["id"])) or {}
                e.update({k: full[k] for k in ("date", "venue", "city", "venueState", "venueCountry", "segments", "broadcasts", "state", "short") if full.get(k)})
                if not full.get("date") and (g.get("date") or "") < (e.get("date") or "9"):
                    e["date"] = g.get("date")
        used = set()
        for eid, e in sorted(evs.items(), key=lambda kv: kv[1].get("date") or ""):
            base = f"{slugify(e['name'])}-{day_et(parse_dt(e['date']))}"
            if base in used:
                base = f"{base}-{eid}"
            used.add(base)
            e["path"] = f"ufc/events/{base}/"
        self.ev = evs

    # helpers ---------------------------------------------------------------
    def team_link(self, t, label=None):
        p = self.team_paths.get(str((t or {}).get("id") or ""))
        lab = label or tname(t)
        return f'<a class="tlink" href="{esc(p)}">{esc(lab)}</a>' if p else esc(lab)

    def matchup(self, g, short=False):
        a, h = g["away"], g["home"]
        if self.lg == "ufc":
            return f"{tname(a)} vs. {tname(h)}"
        n = (lambda t: pv.side_name(t)) if short else tname
        return f"{n(a)} at {n(h)}"

    def lines_brief(self, g):
        """'PHI -6.5 · O/U 54.5' from the reference book."""
        _, b = pv.ref_book(g)
        if not b:
            return ""
        bits = []
        h, a = g["home"], g["away"]
        if self.kind in ("football", "basketball") and isnum(b.get("homeSpread")):
            hs = b["homeSpread"]
            bits.append("PK" if hs == 0 else f"{h.get('abbr')} {line(hs)}" if hs < 0 else f"{a.get('abbr')} {line(-hs)}")
        elif isnum(b.get("homeML")) and isnum(b.get("awayML")):
            fav, ml = (h, b["homeML"]) if b["homeML"] <= b["awayML"] else (a, b["awayML"])
            bits.append(f"{fav.get('abbr') if self.lg != 'ufc' else (fav.get('last') or fav.get('short') or fav.get('name'))} {am(ml)}")
        if isnum(b.get("total")) and self.lg != "ufc":
            bits.append(f"O/U {num(b['total'])}")
        return " · ".join(bits)

    def score_line(self, g):
        a, h = g["away"], g["home"]
        if self.lg == "ufc":
            w = h if h.get("winner") else a if a.get("winner") else None
            res = g.get("result") or {}
            how = " ".join(str(x) for x in [res.get("method"), f"({res['detail']})" if res.get("detail") else "", f"in round {res['round']}" if res.get("round") else "", f"at {res['clock']}" if res.get("clock") else ""] if x)
            return f"{tname(w)} won{(' by ' + how) if how else ''}" if w else (g.get("statusDetail") or "Final")
        return f"{a.get('abbr')} {num(a.get('score'))}, {h.get('abbr')} {num(h.get('score'))}"


