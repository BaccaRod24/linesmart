# ---------------------------------------------------------------- archive
class Archive:
    """games-<lg>.json {id: game} (compact, with "closing" lines), players-<lg>.json {pid: snapshot}, state.json
    {"paths": {lg: {id: [path, old...]}}, "slugs": {lg: {pid: slug}}, "lastmod": {path: [hash, iso]}}."""

    def __init__(self, d: Path | None):
        self.dir = Path(d) if d else None
        self.games, self.players, self._orig = {}, {}, {}
        self.state = {"paths": {}, "slugs": {}, "lastmod": {}}
        if not self.dir:
            return
        for lg in ORDER:
            self.games[lg] = self._load(f"games-{lg}.json", {})
            self.players[lg] = self._load(f"players-{lg}.json", {})
        self.state.update(self._load("state.json", {}))

    def _load(self, name, default):
        v = load_json(self.dir / name)
        self._orig[name] = json.dumps(v, sort_keys=True, separators=(",", ":")) if v is not None else None
        return v if isinstance(v, dict) else default

    def save(self):
        if not self.dir:
            return []
        self.dir.mkdir(parents=True, exist_ok=True)
        files = {f"games-{lg}.json": self.games.get(lg, {}) for lg in ORDER}
        files.update({f"players-{lg}.json": self.players.get(lg, {}) for lg in ORDER})
        files["state.json"] = self.state
        wrote = []
        for name, v in files.items():
            s = json.dumps(v, sort_keys=True, separators=(",", ":"))
            if s != self._orig.get(name):     # only touch files that changed (keeps data-history commits small)
                tmp = self.dir / (name + ".tmp")
                tmp.write_text(s)
                tmp.replace(self.dir / name)
                wrote.append(name)
        return wrote


GAME_KEYS = ["id", "date", "name", "state", "statusDetail", "finalLabel", "completed", "venue", "city", "venueState", "venueCountry", "neutral",
             "broadcasts", "note", "event", "segment", "segmentName", "matchNo", "weightClass", "rounds", "mainEvent", "title", "result", "weather"]
SIDE_KEYS = ["id", "abbr", "name", "short", "last", "logo", "color", "record", "score", "winner", "form", "rank", "country"]


def score_num(v):
    """ESPN sends scores as strings ("24"); pages and grading want numbers."""
    if isnum(v):
        return int(v) if float(v).is_integer() else v
    try:
        f = float(str(v).strip())
    except (TypeError, ValueError):
        return None
    return int(f) if f.is_integer() else f


def norm_scores(g):
    """Copy of g with numeric side scores (no-op when absent)."""
    out = dict(g)
    for s in ("home", "away"):
        if isinstance(g.get(s), dict) and g[s].get("score") not in (None, ""):
            out[s] = dict(g[s], score=score_num(g[s]["score"]))
    return out


def compact(g):
    g = norm_scores(g)
    r = {k: g[k] for k in GAME_KEYS if g.get(k) not in (None, "", [], {})}
    for s in ("home", "away"):
        r[s] = {k: (g.get(s) or {}).get(k) for k in SIDE_KEYS if (g.get(s) or {}).get(k) not in (None, "")}
    if isinstance(r.get("weather"), dict):
        r["weather"] = {k: v for k, v in r["weather"].items() if k != "hours"}
    m = g.get("move") or {}
    if m:
        r["move"] = {k: m[k] for k in ("book", "since", "points", "spread", "total", "homeML", "awayML", "notable", "spark") if k in m}
    return r


def closing_of(g, now=None):
    """Last lines seen before the start. closedAt is the newest book timestamp, else `now` when we first stored them."""
    books = {k: {x: y for x, y in b.items() if x not in ("source", "openSource")} for k, b in pv.live_books(g).items()}
    o = g.get("odds") or {}
    odds = {k: v for k, v in o.items() if k in ("provider", "homeML", "awayML", "homeSpread", "awaySpread", "total", "overOdds", "underOdds", "homeSpreadOdds", "awaySpreadOdds", "details")} if o else None
    if not (books or (odds and any(isnum(odds.get(k)) for k in ("homeML", "homeSpread", "total")))):
        return None
    out = {"books": books, "odds": odds}
    times = [b.get("asOf") for b in books.values() if isinstance(b, dict) and b.get("asOf")]
    if times:
        out["closedAt"] = max(times)
    elif now is not None:
        out["closedAt"] = iso(now)
    return out


def abnormal(g):
    """'postponed' or 'canceled' from the ESPN status text. These are never finals and are never pruned."""
    d = str((g or {}).get("statusDetail") or "").lower()
    if "postpon" in d:
        return "postponed"
    if "cancel" in d:
        return "canceled"
    return ""


def recent_match(gid, dt, opp_abbr, home, rows):
    """The team's recent result that IS this game: same ESPN event id when the row has one, else the same opponent,
    same home/away side and the same ET calendar day. Never "closest game against that opponent": in a series (MLB/NHL/NBA
    playoffs, back-to-back sets) the same two teams meet on consecutive days, and a +-36h window picked the wrong game."""
    for r in rows or []:
        if not isnum(r.get("pf")) or score_num(r.get("pa")) is None:
            continue
        rid = str(r.get("id") or "")
        if rid:
            if rid == str(gid):
                return r
            continue
        rd = parse_dt(r.get("date"))
        if rd and dt and day_et(rd) == day_et(dt) and r.get("opp") == opp_abbr and bool(r.get("home")) == home:
            return r
    return None


def final_from_recent(rec, gid, teams, by_id_only=False):
    """(home score, away score, final label or None) for an archived game from either team's recent results, or None."""
    dt = parse_dt(rec.get("date"))
    h, a = rec.get("home") or {}, rec.get("away") or {}
    for side, other, is_home in ((h, a, True), (a, h, False)):
        rows = (teams.get(str(side.get("id"))) or {}).get("recent") or []
        if by_id_only:
            rows = [r for r in rows if r.get("id")]
        r = recent_match(gid, dt, other.get("abbr"), is_home, rows)
        if r:
            pf, pa = score_num(r["pf"]), score_num(r["pa"])
            return ((pf, pa) if is_home else (pa, pf)) + (r.get("fin"),)
    return None


def merge_archive(arch: Archive, lg, games, teams, now):
    """Fold the current window into the archive and fill finals for games that left the window. Nothing is deleted:
    a finished page stays up after it leaves the data window."""
    if not arch.dir:
        return
    A = arch.games.setdefault(lg, {})
    in_window = set()
    for g in games:
        dt = parse_dt(g.get("date"))
        if not dt or not g.get("id") or not g.get("home") or not g.get("away"):
            continue
        in_window.add(str(g["id"]))
        if g.get("state") == "pre" and dt > now + timedelta(hours=ARCHIVE_AHEAD_H):
            continue
        old = A.get(str(g["id"])) or {}
        rec = compact(g)
        cl = closing_of(g, now) if g.get("state") == "pre" else None
        kept = cl or (old.get("closing") if isinstance(old.get("closing"), dict) else None)
        if kept:
            rec["closing"] = kept
        elif "closing" in old and old.get("closing") is None:
            rec["closing"] = None          # backfill flagged this game: lines were never recorded
        if g.get("state") != "pre" and old.get("move") and not g.get("move"):
            rec["move"] = old["move"]
        A[str(g["id"])] = rec
    # Finals for games that dropped out of the window before ESPN marked them final, from the teams' recent results
    # (matched by ESPN event id, else same opponent + side + ET day; see recent_match). Games still in the window are
    # left alone: ESPN's own live/final copy is the truth there. Archived finals are re-checked against recent rows that
    # carry the event id, which also repairs finals an older build filled in from the wrong game of a series.
    if lg != "ufc":
        for gid, rec in A.items():
            if gid in in_window or abnormal(rec):
                continue
            dt = parse_dt(rec.get("date"))
            if not dt or dt > now - timedelta(hours=3):
                continue
            done = rec.get("state") == "post"
            sc = final_from_recent(rec, gid, teams, by_id_only=done)
            if not sc:
                continue
            hs, as_, fin = sc
            h, a = rec.setdefault("home", {}), rec.setdefault("away", {})
            if done and h.get("score") == hs and a.get("score") == as_:
                if fin and fin != rec.get("finalLabel"):   # right score, label missing (older build): add "Final/OT" etc.
                    rec.update(statusDetail=fin, finalLabel=fin)
                continue
            h["score"], a["score"] = hs, as_
            h["winner"], a["winner"] = hs > as_, as_ > hs
            rec.update(state="post", statusDetail=fin or "Final", completed=True)
            if fin:
                rec["finalLabel"] = fin
            else:
                rec.pop("finalLabel", None)


