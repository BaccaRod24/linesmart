def result_card(L: League, g):
    """Final score and how the closing lines graded (descriptive only)."""
    a, h = g["away"], g["home"]
    if L.lg == "ufc":
        res = L.score_line(g)
        _, b = pv.ref_book(g)
        bits = [res + "."]
        if b and isnum(b.get("homeML")) and isnum(b.get("awayML")):
            w = h if h.get("winner") else a if a.get("winner") else None
            if w:
                ml = b["homeML"] if w is h else b["awayML"]
                bits.append(f"{tname(w)} closed at {am(ml)} ({'favorite' if ml < 0 and ml <= min(b['homeML'], b['awayML']) else 'underdog' if ml > 0 else 'pick'}).")
        return f'<div class="card sx-result"><h3>Result</h3><p>{esc(" ".join(bits))}</p></div>'
    sa, sh = a.get("score"), h.get("score")
    if not (isnum(sa) and isnum(sh)):
        return ""
    bits = [f"Final: {tname(a)} {num(sa)}, {tname(h)} {num(sh)}."]
    _, b = pv.ref_book(g)
    if b and g.get("_closing"):
        hs = b.get("homeSpread")
        if isnum(hs) and L.kind in ("football", "basketball"):
            m = (sh - sa) + hs
            bits.append("The closing spread was a push." if m == 0 else f"{(h if m > 0 else a).get('abbr')} covered the closing spread ({(h if m > 0 else a).get('abbr')} {line(hs if m > 0 else -hs)}).")
        t = b.get("total")
        if isnum(t):
            tot = sa + sh
            bits.append(f"{num(tot)} total {UNIT.get(L.kind, 'point')}s vs a closing total of {num(t)}: " + ("push." if tot == t else "over." if tot > t else "under."))
    elif not g.get("_closing"):
        bits.append("We didn't record lines for this game before it started.")
    return f'<div class="card sx-result"><h3>Final score</h3><p>{esc(" ".join(bits))}</p></div>'


def game_props(L: League, gid):
    rows = ((L.props.get("games") or {}).get(gid) or {}).get("props") or []
    if not rows:
        return "", []
    P = L.props.get("players") or {}
    best = {}
    for r in rows:     # one row per player: the market with the most books (then first listed)
        pid = str(r[0])
        nb = len(r[5]) if len(r) > 5 and isinstance(r[5], dict) else 0
        if pid not in best or nb > best[pid][0]:
            best[pid] = (nb, r)
    trs, links = [], []
    for pid, (_, r) in sorted(best.items(), key=lambda kv: ((P.get(kv[0]) or {}).get("ta") or "", (P.get(kv[0]) or {}).get("n") or "")):
        pl = P.get(pid) or {}
        pe = L.players.get(pid) or {}
        path = pe.get("path")
        name = f'<a href="{esc(path)}">{esc(pl.get("n") or pid)}</a>' if path else esc(pl.get("n") or pid)
        mk = r[1]
        rt = rate(pl.get("log"), mk, r[2], 5)
        trs.append(f'<tr><td>{name} <span class="na">{esc(pl.get("ta") or "")} {esc(pl.get("pos") or "")}</span></td><td>{esc((L.markets.get(mk) or [mk])[0])}</td>'
                   f'<td class="num">{esc(line_text(mk, r[2]))}</td><td>{strip_html(pl.get("log"), mk, r[2])}</td><td class="num">{rt["o"]}/{rt["n"]}</td></tr>')
        if path:
            n_mk = sum(1 for x in rows if str(x[0]) == pid)
            links.append((path, f"{pl.get('n')} props", f"{pl.get('ta') or ''} · {plural(n_mk, 'line')}"))
    tbl = (f'<div class="card"><div class="tbl-wrap pv-tbl"><table class="books sx-props"><thead><tr><th>Player</th><th>Market</th><th>Line</th><th>Last 5 vs line</th><th>Over</th></tr></thead>'
           f'<tbody>{"".join(trs)}</tbody></table></div>{PP_LEGEND}<p class="pp-note-l note">'
           f'{len(rows)} prop lines across {plural(len(best), "player")}; each player page has every line. Past results only, not a prediction.</p></div>')
    return tbl, links


def weather_card(g):
    wx = g.get("weather") or {}
    if not wx.get("label"):
        return ""
    bits = []
    if wx.get("roof") in ("dome", "closed", "indoor"):
        bits.append("Indoor stadium: weather won't be a factor.")
    if isnum(wx.get("temp")):
        bits.append(f"{num(wx['temp'])}°F{(' (feels like ' + num(wx['feels']) + '°F)') if isnum(wx.get('feels')) and wx.get('feels') != wx.get('temp') else ''}")
    if isnum(wx.get("wind")):
        bits.append(f"wind {num(wx['wind'])} mph{(' ' + wx['dirTxt']) if wx.get('dirTxt') else ''}{(', gusts ' + num(wx['gust'])) if isnum(wx.get('gust')) and wx.get('gust', 0) > wx.get('wind', 0) else ''}")
    if isnum(wx.get("pop")):
        bits.append(f"{num(wx['pop'])}% chance of {wx.get('precipType') or 'precipitation'}")
    roof = f" Roof: {wx['roof']}." if wx.get("roof") and wx.get("roof") not in ("open", "none") else ""
    asof = parse_dt(wx.get("asOf"))
    return (f'<div class="card sx-wx"><h3>{esc(wx.get("label"))}{(" · " + esc(wx.get("place"))) if wx.get("place") else ""}</h3>'
            f'<p>{esc(", ".join(bits))}.{esc(roof)}</p><div class="note">{"Forecast" if wx.get("kind") == "forecast" else "Conditions"} at kickoff from Open-Meteo{(", as of " + esc(fmt_et(asof, False))) if asof else ""}.</div></div>')


def related_games(L: League, g, limit=10):
    gid = str(g["id"])
    d = day_et(parse_dt(g["date"]))
    tids = {str(g["home"].get("id")), str(g["away"].get("id"))}
    same_team, same_day = [], []
    for oid, o in L.games.items():
        if oid == gid:
            continue
        od = parse_dt(o["date"])
        note = (L.score_line(o) if L.is_final(o) else fmt_et(od, False))
        item = (od, (L.paths[oid], L.matchup(o), note))
        if {str(o["home"].get("id")), str(o["away"].get("id"))} & tids:
            same_team.append(item)
        elif day_et(od) == d or (L.lg == "ufc" and (o.get("event") or {}).get("id") == (g.get("event") or {}).get("id")):
            same_day.append(item)
    same_team.sort(key=lambda x: x[0], reverse=True)
    same_day.sort(key=lambda x: x[0])
    return [x[1] for x in same_team[:limit]], [x[1] for x in same_day[:limit]]


