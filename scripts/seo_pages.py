"""Build LineSmart's crawlable pages: league hubs, game, player-props, team, UFC event and fighter pages.

Runs offline in the refresh job after build_data.py, from the JSON already in site/data (never calls an odds API).
Every page is real static HTML made from site/index.html (same header, footer, 21+ notices and app scripts), with its
own title, description, canonical, Open Graph tags and JSON-LD. Hub and upcoming-game pages also set data-route so the
app takes over #app with the live view; the other pages stay static and the app only runs the chrome (tabs, state,
offers). Sportsbook offers are never written into the HTML: assets/geo.js fills [data-offers-slot] by state.

Outputs (all generated, git-ignored):
  site/<lg>/...                      pages (see docs/seo-pages.md for the URL pattern)
  site/preview/**                    redirect stubs for the old /preview/ URLs (canonical -> new page)
  site/data/pages.json               hash route -> real URL manifest used by app.js (redirects + link rewriting)
  site/sitemap.xml                   the <!-- pages:start/end --> block, with lastmod
  site/index.html                    the <!-- seo:home:start/end --> block (mobile homepage cards)

Finished games stay up about 60 days with the final score and the last lines we saw before the start (closing lines).
That needs an archive that outlives the rolling data window: --archive DIR (env ARCHIVE_DIR; the workflow keeps it on
the data-history branch). Without it only games still in site/data get pages.
"""
