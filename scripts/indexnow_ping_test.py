#!/usr/bin/env python3
"""indexnow_ping.py: sitemap diff, one batched POST, skips, error handling and the committed key file. No network:
urllib.request.urlopen is replaced, and any real network attempt fails the test."""
from __future__ import annotations

import io
import json
import re
import socket
import sys
import tempfile
import urllib.error
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import indexnow_ping as IN  # noqa: E402
import seo_pages as SP  # noqa: E402

passed = failed = 0


def check(ok, msg):
    global passed, failed
    if ok:
        passed += 1
    else:
        failed += 1
        print("FAIL:", msg)


def no_net(*a, **k):
    raise AssertionError("test tried to open a network connection")


socket.create_connection = no_net
socket.socket.connect = lambda *a, **k: no_net()

calls = []


class Resp:
    def __init__(self, status, body=b""):
        self.status, self._b = status, body

    def read(self, n=-1):
        return self._b

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


def fake(status=200, exc=None):
    def urlopen(req, timeout=None):
        calls.append({"url": req.full_url, "method": req.get_method(), "headers": dict(req.header_items()), "body": json.loads(req.data)})
        if exc:
            raise exc
        if status >= 400:
            raise urllib.error.HTTPError(req.full_url, status, "err", {}, io.BytesIO(b"nope"))
        return Resp(status)
    IN.urllib.request.urlopen = urlopen


def sitemap(pages, home="2026-10-28T12:00:00+00:00"):
    rows = "".join(f"<url><loc>{u}</loc><lastmod>{lm}</lastmod></url>\n" for u, lm in pages.items())
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"<url><loc>https://linesmart.app/</loc><lastmod>{home}</lastmod></url>\n"
            f"<!-- pages:start (generated by scripts/seo_pages.py) -->\n{rows}<!-- pages:end -->\n</urlset>\n")


B = "https://linesmart.app"
old = {f"{B}/nfl/": "2026-10-27T10:00:00+00:00", f"{B}/nfl/games/a-at-b-2026-11-01/": "2026-10-27T10:00:00+00:00",
       f"{B}/nba/teams/x/": "2026-10-20T10:00:00+00:00", f"{B}/nba/games/gone-2026-10-20/": "2026-10-20T10:00:00+00:00"}
new = {f"{B}/nfl/": "2026-10-27T10:00:00+00:00", f"{B}/nfl/games/a-at-b-2026-11-01/": "2026-10-28T12:00:00+00:00",
       f"{B}/nba/teams/x/": "2026-10-20T10:00:00+00:00", f"{B}/nfl/games/c-at-d-2026-11-02/": "2026-10-28T12:00:00+00:00",
       "https://evil.example/x/": "2026-10-28T12:00:00+00:00"}

with tempfile.TemporaryDirectory() as td:
    td = Path(td)
    site = td / "site"
    site.mkdir()
    key = "0123456789abcdef0123456789abcdef"
    (site / f"{key}.txt").write_text(key)
    (site / "robots.txt").write_text("User-agent: *")
    prev_f, new_f = td / "prev.xml", td / "new.xml"
    prev_f.write_text(sitemap(old, "2026-10-27T10:00:00+00:00"))
    new_f.write_text(sitemap(new))

    # ---- parsing + diff
    e = IN.entries(new_f.read_text())
    check(e and f"{B}/" not in e and len(e) == 5, f"only the generated pages block is compared (homepage lastmod ignored) ({e and len(e)})")
    ch = IN.changed(IN.entries(prev_f.read_text()), e)
    check(ch == [f"{B}/nfl/games/a-at-b-2026-11-01/", f"{B}/nfl/games/c-at-d-2026-11-02/"], f"new + re-dated URLs on our host only, removed ones not sent ({ch})")
    check(IN.entries("not xml") is None and IN.entries("") is None and IN.entries(None) is None, "garbage / empty baseline is no baseline")
    check(IN.entries('<urlset><url><loc>https://linesmart.app/a/</loc><lastmod>1</lastmod></url></urlset>') == {"https://linesmart.app/a/": "1"}, "sitemap without markers: all entries")
    check(IN.entries('<sitemapindex><sitemap><loc>https://linesmart.app/sitemap-core.xml</loc></sitemap></sitemapindex>') is None, "entries() does not treat an index as a urlset")

    # sitemap index: child files beside the index, generated block only, missing child is no baseline
    idx = td / "idx"
    prev_d, new_d = idx / "prev", idx / "new"
    prev_d.mkdir(parents=True)
    new_d.mkdir()
    def urlset(rows, static=""):
        body = "".join(f"<url><loc>{u}</loc><lastmod>{lm}</lastmod></url>\n" for u, lm in rows.items())
        return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                f"{static}<!-- pages:start -->\n{body}<!-- pages:end -->\n</urlset>\n")
    (prev_d / "sitemap-core.xml").write_text(urlset({f"{B}/nfl/": "2026-10-27T10:00:00+00:00"}, f"<url><loc>{B}/</loc><lastmod>2026-10-01</lastmod></url>\n"))
    (prev_d / "sitemap-live.xml").write_text(urlset({f"{B}/nfl/games/a-at-b-2026-11-01/": "2026-10-27T10:00:00+00:00"}))
    (new_d / "sitemap-core.xml").write_text(urlset({f"{B}/nfl/": "2026-10-27T10:00:00+00:00"}, f"<url><loc>{B}/</loc><lastmod>2026-10-28</lastmod></url>\n"))
    (new_d / "sitemap-live.xml").write_text(urlset({f"{B}/nfl/games/a-at-b-2026-11-01/": "2026-10-28T12:00:00+00:00", f"{B}/nfl/games/c-at-d-2026-11-02/": "2026-10-28T12:00:00+00:00"}))
    index_xml = ('<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                 f"<sitemap><loc>{B}/sitemap-core.xml</loc></sitemap>\n<sitemap><loc>{B}/sitemap-live.xml</loc></sitemap>\n</sitemapindex>\n")
    (prev_d / "sitemap.xml").write_text(index_xml)
    (new_d / "sitemap.xml").write_text(index_xml)
    loaded = IN.load_entries(new_d / "sitemap.xml")
    check(loaded and f"{B}/" not in loaded and f"{B}/nfl/games/c-at-d-2026-11-02/" in loaded, f"index reads child urlsets and skips static URLs ({loaded and sorted(loaded)})")
    ch2 = IN.changed(IN.load_entries(prev_d / "sitemap.xml"), loaded)
    check(ch2 == [f"{B}/nfl/games/a-at-b-2026-11-01/", f"{B}/nfl/games/c-at-d-2026-11-02/"], f"index diff is new or re-dated pages only ({ch2})")
    calls.clear(); fake(200)
    r = IN.run(prev_d / "sitemap.xml", new_d / "sitemap.xml", site)
    check(r["sent"] == 2 and calls and calls[-1]["body"]["urlList"] == ch2, f"ping submits only the index diff ({r})")
    (prev_d / "sitemap-live.xml").unlink()
    check(IN.load_entries(prev_d / "sitemap.xml") is None, "index with a missing child is not a baseline")
    calls.clear()
    r = IN.run(prev_d / "sitemap.xml", new_d / "sitemap.xml", site)
    check(not calls and r["skipped"] == "no baseline", "missing child -> skip, no blind resubmit")
    (prev_d / "sitemap-live.xml").write_text(urlset({f"{B}/nfl/games/a-at-b-2026-11-01/": "2026-10-27T10:00:00+00:00"}))
    check(len(IN.changed({}, {f"{B}/p{i}/": "1" for i in range(12000)})) == IN.MAX_URLS == 10000, "capped at 10,000 URLs")
    check(IN.find_key(site) == key, "finds the key file")

    # ---- one POST with host, key, keyLocation, urlList
    calls.clear(); fake(200)
    r = IN.run(prev_f, new_f, site)
    check(len(calls) == 1 and r["sent"] == 2 and r["status"] == 200, f"one POST per run ({len(calls)} calls, {r})")
    c = calls[0] if calls else {}
    check(c.get("url") == "https://api.indexnow.org/indexnow" and c.get("method") == "POST", "POSTs to api.indexnow.org/indexnow")
    check(c.get("body") == {"host": "linesmart.app", "key": key, "keyLocation": f"https://linesmart.app/{key}.txt", "urlList": ch}, f"payload: host, key, keyLocation, urlList ({c.get('body')})")
    check("application/json" in (c.get("headers") or {}).get("Content-type", ""), "JSON content type")

    # ---- skips: nothing new, no baseline, no key, dry run
    calls.clear()
    r = IN.run(new_f, new_f, site)
    check(not calls and r["skipped"] == "nothing new", "nothing new -> no request")
    r = IN.run(td / "missing.xml", new_f, site)
    check(not calls and r["skipped"] == "no baseline", "live sitemap fetch failed -> skip, no blind resubmit")
    bad = td / "bad.xml"; bad.write_text("<html>502 Bad Gateway</html>")
    r = IN.run(bad, new_f, site)
    check(not calls and r["skipped"] == "no baseline", "error page instead of a sitemap -> skip")
    empty = td / "empty"; empty.mkdir()
    r = IN.run(prev_f, new_f, empty)
    check(not calls and r["skipped"] == "no key", "no key file -> skip")
    r = IN.run(prev_f, new_f, site, dry_run=True)
    check(not calls and r["skipped"] == "dry run", "--dry-run sends nothing")
    r = IN.run(prev_f, td / "missing.xml", site)
    check(not calls and r["skipped"] == "no new sitemap", "no deployed sitemap -> skip")

    # ---- errors are logged, never raised; exit code is always 0
    for st in (400, 403, 422, 429, 500):
        calls.clear(); fake(st)
        r = IN.run(prev_f, new_f, site)
        check(len(calls) == 1 and r["status"] == st and r["sent"] == 0, f"HTTP {st}: logged, one attempt, no retry")
    calls.clear(); fake(202)
    check(IN.run(prev_f, new_f, site)["sent"] == 2, "HTTP 202 (key pending) counts as received")
    calls.clear(); fake(exc=urllib.error.URLError("dns down"))
    r = IN.run(prev_f, new_f, site)
    check(len(calls) == 1 and r["skipped"].startswith("error"), "network error caught")
    calls.clear(); fake(exc=TimeoutError("timed out"))
    check(IN.main(["--prev", str(prev_f), "--new", str(new_f), "--site", str(site)]) == 0, "main() exits 0 on timeout")
    check(IN.main(["--bogus"]) == 0, "main() exits 0 on bad arguments")
    IN.urllib.request.urlopen = no_net

# ---- the committed key file: site/<32 hex>.txt containing exactly the key, outside generated / cleaned dirs
keys = [f for f in IN.SITE.glob("*.txt") if re.fullmatch(r"[0-9a-f]{32}", f.stem)]
check(len(keys) == 1, f"exactly one IndexNow key file in site/ ({[k.name for k in keys]})")
if keys:
    k = keys[0]
    check(k.read_text(encoding="utf-8").strip() == k.stem and re.fullmatch(r"[0-9a-f]{32}", k.read_text().strip()), "key file contains its own 32-hex key")
    check(k.parent == IN.SITE and k.parent.name not in SP.GEN_DIRS, "key file sits at the site root (served at https://linesmart.app/<key>.txt), not in a generated dir")
    check(IN.find_key() == k.stem, "script finds the committed key")
wf = (IN.SITE.parent / ".github/workflows/refresh-and-deploy.yml").read_text()
check("indexnow_ping.py" in wf and re.search(r"indexnow:\n(?:.*\n)*?\s+needs: \[?build, deploy\]?|indexnow:\n(?:.*\n)*?\s+needs: deploy", wf), "workflow runs the ping after the deploy job")
check(re.search(r"refs/heads/main", wf.split("indexnow:", 1)[-1] if "indexnow:" in wf else ""), "ping only for main")

print(f"{'PASS' if not failed else 'FAIL'} indexnow_ping: {passed}/{passed + failed}")
sys.exit(1 if failed else 0)
