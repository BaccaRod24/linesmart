def big_moves(L: League, n=6):
    out = []
    for gid, g in upcoming(L):
        m = g.get("move") or {}
        h, a = g["home"], g["away"]
        sp, tt = m.get("spread") or {}, m.get("total") or {}
        cand = []
        if isnum(sp.get("open")) and isnum(sp.get("cur")) and sp["open"] != sp["cur"] and L.kind in ("football", "basketball"):
            cand.append((abs(sp["cur"] - sp["open"]), "Spread", f"{h.get('abbr')} {line(sp['open'])} → {line(sp['cur'])}"))
        if isnum(tt.get("open")) and isnum(tt.get("cur")) and tt["open"] != tt["cur"]:
            cand.append((abs(tt["cur"] - tt["open"]) * (0.6 if L.kind in ("football", "basketball") else 2), "Total", f"{num(tt['open'])} → {num(tt['cur'])}"))
        ml = m.get("homeML") or {}
        if not cand and isnum(ml.get("open")) and isnum(ml.get("cur")) and ml["open"] != ml["cur"] and L.kind in ("hockey", "baseball", "mma"):
            d = abs(ml["cur"] - ml["open"])
            if d >= 20:
                cand.append((d / 20, "Moneyline", f"{h.get('abbr') if L.lg != 'ufc' else h.get('last')} {am(ml['open'])} → {am(ml['cur'])}"))
        if cand:
            sc, what, txt = max(cand)
            out.append((sc, L.lg, gid, g, what, txt))
    out.sort(key=lambda x: (-x[0], x[3]["date"]))
    return out[:n]


def hot_props(L: League, n=10):
    P = L.props.get("players") or {}
    out = []
    for gid, g in upcoming(L):
        for r in ((L.props.get("games") or {}).get(gid) or {}).get("props") or []:
            pid = str(r[0])
            pl = P.get(pid)
            pe = L.players.get(pid)
            if not pl or not pe or not is_hot(pl.get("log"), r[1], r[2]):
                continue
            rt = rate(pl.get("log"), r[1], r[2], 5)
            nb = len(r[5]) if len(r) > 5 and isinstance(r[5], dict) else 0
            out.append((rt["o"] / max(rt["n"], 1), rt["n"], nb, r[1] != "anytime_td", L.lg, pid, pl, r, g))
    out.sort(key=lambda x: (-x[0], -x[1], -x[3], -x[2], x[8]["date"]))
    seen, res = set(), []
    for x in out:
        if x[5] in seen:
            continue
        seen.add(x[5])
        res.append(x)
        if len(res) >= n:
            break
    return res


