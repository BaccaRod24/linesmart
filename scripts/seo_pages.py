def _best_line(books, fn):
    win = None
    for k, b in books.items():
        got = fn(b)
        if not got:
            continue
        disp, score = got
        if win is None or score > win[0]:
            win = (score, k, disp)
    return win


def line_cell(g, books, names, kind):
    """Plain text for one market: the best price among this state's books, or an em dash."""
    def spread(b):
        sp = b.get("homeSpread")
        if not isnum(sp):
            return None
        price = b.get("homeSpreadOdds")
        score = sp * 1000 + (price if isnum(price) else -110)
        abbr = (g.get("home") or {}).get("abbr") or "Home"
        od = f" ({am(price)})" if isnum(price) else ""
        return (f"{abbr} {line(sp)}{od}", score)

    def total(b):
        t = b.get("total")
        if not isnum(t):
            return None
        price = b.get("overOdds")
        od = f" ({am(price)})" if isnum(price) else ""
        return (f"O/U {num(t)}{od}", price if isnum(price) else -110)

    def ml(b):
        hml, aml = b.get("homeML"), b.get("awayML")
        if not isnum(hml) and not isnum(aml):
            return None
        bits = []
        if isnum(aml):
            bits.append(f"{(g.get('away') or {}).get('abbr') or 'Away'} {am(aml)}")
        if isnum(hml):
            bits.append(f"{(g.get('home') or {}).get('abbr') or 'Home'} {am(hml)}")
        return (" / ".join(bits), hml if isnum(hml) else -10000)

    fn = {"spread": spread, "total": total, "ml": ml}[kind]
    win = _best_line(books, fn)
    if not win:
        return "—"
    _, k, disp = win
    if len(books) > 1 and names.get(k):
        return f"{disp} {names[k]}"
    return disp


def state_slate(Ls, now, keys, limit=12):
    """Next upcoming games that have a line from one of this state's books."""
    rows = []
    for lg, L in Ls.items():
        for gid, g in L.games.items():
            if gid not in L.paths or L.is_final(g):
                continue
            dt = parse_dt(g.get("date"))
            if not dt or dt < now - timedelta(hours=8):
                continue
            live = pv.live_books(g)
            lines = {k: live[k] for k in keys if k in live}
            if keys and not lines:
                continue
            rows.append((dt, lg, gid, g, L, lines))
    rows.sort(key=lambda r: (r[0], ORDER.index(r[1]) if r[1] in ORDER else 99, r[2]))
    return rows[:limit]


