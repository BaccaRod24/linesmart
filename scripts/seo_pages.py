def home_cards(Ls, now):
    """Mobile-first strip for the top of the homepage: today's top games, biggest moves, hot props. Links only to real URLs."""
    today = day_et(now)
    tops = []
    for pri, lg in enumerate(ORDER):
        L = Ls.get(lg)
        if not L:
            continue
        for gid, g in upcoming(L):
            dt = parse_dt(g["date"])
            if pv.has_line(g) or g.get("state") == "in":
                tops.append((day_et(dt) != today, dt > now + timedelta(hours=36), pri, dt, lg, gid, g))
    tops.sort(key=lambda x: x[:4])
    seen_lg, top = {}, []
    for x in tops:          # spread across leagues: at most 3 per league in the first pass
        if seen_lg.get(x[4], 0) < 3:
            top.append(x)
            seen_lg[x[4]] = seen_lg.get(x[4], 0) + 1
        if len(top) >= 8:
            break
    moves = sorted([m for L in Ls.values() for m in big_moves(L, 4)], key=lambda m: (-m[0], m[3]["date"]))[:8]
    hp = sorted([p for L in Ls.values() for p in hot_props(L, 6)], key=lambda x: (-x[0], -x[1], -x[3], -x[2]))[:8]
    def row(rid, title, sub, tiles, more_href=None):
        if not tiles:
            return ""
        return (f'<section class="hc-row" aria-labelledby="{rid}"><div class="hc-h"><h2 id="{rid}">{title}</h2>{f"<span>{sub}</span>" if sub else ""}</div>'
                f'<div class="hc-scroll">{"".join(tiles)}</div></section>')
    any_today = any(not x[0] for x in top)
    html_ = "".join([
        row("hcTop", "Top games today" if any_today else "Top upcoming games", "Best line across books", [game_tile(Ls[x[4]], x[5], x[6], True) for x in top]),
        row("hcMoves", "Biggest line moves", "Since open", [move_tile(m, Ls) for m in moves]),
        row("hcHot", "Hot props", "Last 5 vs the line", [prop_tile(p, Ls) for p in hp]),
    ])
    hubs = "".join(f'<a href="{lg}/">{esc(SHORT[lg])}</a>' for lg in ORDER if lg in Ls)
    return f'<div class="home-cards" id="homeCards">{html_}<nav class="hc-hubs" aria-label="Sports">{hubs}</nav></div>' if html_ else ""


# ---------------------------------------------------------------- redirects, sitemap, homepage
def redirect_stub(from_path, to_path, base_url, title):
    """Old URL -> new page: canonical + meta refresh + JS replace (GitHub Pages can't send 301s). No <base>: explicit relative URL."""
    depth = from_path.count("/")
    rel = "../" * depth + to_path
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)}</title>
<link rel="canonical" href="{esc(base_url + to_path)}">
<meta http-equiv="refresh" content="0; url={esc(rel)}">
<script>location.replace({json.dumps(rel)} + location.hash);</script>
<style>body{{background:#050b1c;color:#e6edf7;font:15px/1.5 system-ui,sans-serif;padding:40px 20px}}a{{color:#3d9bff}}</style>
</head><body><p>This page moved to <a href="{esc(rel)}">{esc(title)}</a>.</p>
<p><small>21+ only. Gambling problem? {build_pages.RG_CALL_STATIC}</small></p></body></html>
"""


def update_sitemap(path: Path, entries, generated):
    txt = path.read_text()
    txt = re.sub(r"[ \t]*<!-- previews:start -->.*?<!-- previews:end -->\n?", "", txt, flags=re.S)  # retired previews.py block
    block = MAP_START + "\n" + "".join(f"  <url><loc>{esc(u)}</loc><lastmod>{lm}</lastmod></url>\n" for u, lm in entries) + "  " + MAP_END
    if MAP_START in txt:
        txt = re.sub(re.escape(MAP_START) + r".*?" + re.escape(MAP_END), lambda _: block, txt, flags=re.S)
    else:
        txt = txt.replace("</urlset>", "  " + block + "\n</urlset>")
    # the homepage changes every refresh (homepage cards)
    txt = re.sub(r"(<loc>" + re.escape(BASE_URL) + r"</loc><lastmod>)[^<]*(</lastmod>)", lambda m: m.group(1) + generated + m.group(2), txt, count=1)
    path.write_text(txt)


def update_home(index: Path, cards_html):
    txt = index.read_text()
    if HOME_START not in txt:
        return False
    txt = re.sub(re.escape(HOME_START) + r".*?" + re.escape(HOME_END), lambda _: HOME_START + cards_html + HOME_END, txt, flags=re.S)
    index.write_text(txt)
    return True


# ---------------------------------------------------------------- build
def build(site: Path, data_dir: Path, now: datetime, base_url=BASE_URL, archive_dir=None, write_site_files=True):
    t0 = time.time()
    meta = load_json(data_dir / "meta.json") or {}
    generated = parse_dt(meta.get("generated")) or now
    index_path = site / "index.html"
    sh = Shell(index_path.read_text(), base_url)
    arch = Archive(archive_dir)
    Ls = {}
    for lg in ORDER:
        # a league with no data this run (offseason, feed down) still gets its hub, so footer/hub links never 404
        raw = load_json(data_dir / lg / "index.json")
        ix = raw or {"games": [], "teams": {}}
        props = load_json(data_dir / "props" / f"{lg}.json") if lg != "ufc" else None
        L = League(lg, ix, props, arch, now, base_url)
        L.data_dir = data_dir
        L.has_data = bool(raw)
        merge_archive(arch, lg, ix.get("games") or [], L.teams, now)
        L.select()
        L.assign_paths()
        L.collect_players()
        L.collect_teams()
        L.collect_events()
        Ls[lg] = L
    tmp = site / ".seo.tmp"
    shutil.rmtree(tmp, ignore_errors=True)
    pages, titles, stats = {}, {}, {}
    manifest = {"generated": iso(now), "l": {}, "g": {}, "t": {}, "p": {}}

    def put(path, html, title, kind, lg):
        pages[path] = html
        titles.setdefault(title, []).append(path)
        stats.setdefault(lg, {}).setdefault(kind, 0)
        stats[lg][kind] += 1

    for lg, L in Ls.items():
        html, t = hub_page(L, sh, Ls)
        put(L.hub, html, t, "hub", lg)
        manifest["l"][lg] = L.hub
        for gid in L.games:
            html, t = game_page(L, sh, gid)
            put(L.paths[gid], html, t, "past" if L.is_final(L.games[gid]) else "game", lg)
            manifest["g"].setdefault(lg, {})[gid] = L.paths[gid]
        for pid in L.players:
            html, t = player_page(L, sh, pid)
            put(L.players[pid]["path"], html, t, "player", lg)
            manifest["p"].setdefault(lg, {})[pid] = L.players[pid]["path"]
        for tid in L.team_paths:
            html, t = team_page(L, sh, tid)
            put(L.team_paths[tid], html, t, "fighter" if lg == "ufc" else "team", lg)
            manifest["p" if lg == "ufc" else "t"].setdefault(lg, {})[tid] = L.team_paths[tid]
        for eid in getattr(L, "ev", {}):
            html, t = event_page(L, sh, eid)
            put(L.ev[eid]["path"], html, t, "event", lg)
    # titles must be unique: disambiguate the rare collision with the page's own path
    for t, ps in titles.items():
        if len(ps) > 1:
            for p in ps[1:]:
                tail = p.strip("/").rsplit("/", 1)[-1]
                pages[p] = pages[p].replace(f"<title>{esc(t)}</title>", f"<title>{esc(t.replace(' · LineSmart', ''))} ({esc(tail)}) · LineSmart</title>", 1)
    # redirects: old /preview/ URLs and older paths of rescheduled games
    redirects = {}
    for lg, L in Ls.items():
        used = set()
        for gid, g in sorted(((k, v) for k, v in L.games.items() if k in L.current), key=lambda kv: (kv[1]["date"], kv[0])):
            redirects[pv.page_path(lg, g, used)] = (L.paths[gid], L.matchup(g))
            for op in L.old_paths.get(gid, []):
                if op not in pages:
                    redirects[op] = (L.paths[gid], L.matchup(g))
        redirects[f"preview/{lg}/"] = (L.hub, f"{NAMES[lg]} odds")
    redirects["preview/"] = ("", "LineSmart")
    # lastmod: only moves when the page content (minus build stamps) changes
    lm_state = arch.state.setdefault("lastmod", {}) if arch.dir else {}
    stamp_now = iso(now)
    entries = []
    for path in sorted(pages, key=lambda p: (p.count("/"), p)):
        h = content_hash(pages[path])
        old = lm_state.get(path)
        lm = old[1] if old and old[0] == h else stamp_now
        if arch.dir:
            lm_state[path] = [h, lm]
        entries.append((base_url + path, lm))
    if arch.dir:
        for p in [p for p in lm_state if p not in pages]:
            del lm_state[p]
    # write: build in .seo.tmp, then swap each top-level dir
    for path, html in pages.items():
        f = tmp / path / "index.html"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(html)
    for path, (to, title) in redirects.items():
        f = tmp / path / "index.html"
        if f.exists():
            continue
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(redirect_stub(path, to, base_url, title))
    nbytes = sum(f.stat().st_size for f in tmp.rglob("*") if f.is_file())
    for d in GEN_DIRS:
        final, new, old = site / d, tmp / d, site / f".{d}.old"
        shutil.rmtree(old, ignore_errors=True)
        if final.exists():
            final.rename(old)
        if new.exists():
            new.rename(final)
        shutil.rmtree(old, ignore_errors=True)
    shutil.rmtree(tmp, ignore_errors=True)
    (data_dir / "pages.json").write_text(json.dumps(manifest, separators=(",", ":")))
    if meta:
        meta.pop("previews", None)
        meta["pages"] = {"generated": iso(now), "count": len(pages)}
        (data_dir / "meta.json").write_text(json.dumps(meta, indent=1))
    if write_site_files:
        if (site / "sitemap.xml").exists():
            update_sitemap(site / "sitemap.xml", entries, iso(generated))
        update_home(index_path, home_cards(Ls, now))
    wrote = arch.save()
    total = {}
    for v in stats.values():
        for k, n in v.items():
            total[k] = total.get(k, 0) + n
    return {"leagues": stats, "total": total, "pages": len(pages), "redirects": len(redirects), "bytes": nbytes,
            "archive": {lg: len(v) for lg, v in arch.games.items()} if arch.dir else None, "archiveWrote": wrote, "seconds": round(time.time() - t0, 2)}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--site", default=str(ROOT / "site"))
    ap.add_argument("--data", default=None, help="data directory (default: <site>/data)")
    ap.add_argument("--archive", default=os.environ.get("ARCHIVE_DIR") or None, help="finished-games archive dir (env ARCHIVE_DIR)")
    ap.add_argument("--now", default=None, help="ISO time to treat as now (tests)")
    ap.add_argument("--base-url", default=BASE_URL)
    ap.add_argument("--no-site-files", action="store_true", help="don't touch site/index.html and site/sitemap.xml")
    a = ap.parse_args(argv)
    site = Path(a.site)
    data_dir = Path(a.data) if a.data else site / "data"
    now = parse_dt(a.now) if a.now else datetime.now(timezone.utc)
    s = build(site, data_dir, now, a.base_url, a.archive, write_site_files=not a.no_site_files)
    lg = "; ".join(f"{k} " + ", ".join(f"{n} {t}" for t, n in v.items()) for k, v in s["leagues"].items())
    print(f"seo pages: {s['pages']} pages + {s['redirects']} redirects, {s['bytes'] / 1e6:.1f} MB, {s['seconds']}s ({lg})")
    if s["archive"] is not None:
        print(f"seo archive: {s['archive']} (wrote {', '.join(s['archiveWrote']) or 'nothing'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
