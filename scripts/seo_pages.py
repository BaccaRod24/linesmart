def related_games(L: League, g, limit=10):
    gid = str(g["id"])
    d = day_et(parse_dt(g["date"]))
    tids = {str(g["home"].get("id")), str(g["away"].get("id"))}
    same_team, same_day = [], []
    for oid, o in L.games.items():
        if oid == gid:
            continue
        od = parse_dt(o["date"])
        note = (L.score_line(o) if L.is_final(o) else fmt_et(od, False))
        item = (od, (L.paths[oid], L.matchup(o), note))
        if {str(o["home"].get("id")), str(o["away"].get("id"))} & tids:
            same_team.append(item)
        elif day_et(od) == d or (L.lg == "ufc" and (o.get("event") or {}).get("id") == (g.get("event") or {}).get("id")):
            same_day.append(item)
    same_team.sort(key=lambda x: x[0], reverse=True)
    same_day.sort(key=lambda x: x[0])
    return [x[1] for x in same_team[:limit]], [x[1] for x in same_day[:limit]]


def next_games(L: League, g):
    """Each side's next scheduled game after this one that has a page: [(side, gid, game)] (away first).
    Only games already in the generated data (L.games / L.paths), never a made-up URL.
    Postponed and canceled games are not a team's next game."""
    gid, dt = str(g["id"]), parse_dt(g["date"])
    out = []
    for t in (g["away"], g["home"]):
        tid = str((t or {}).get("id") or "")
        best = None
        for oid, o in L.games.items():
            if oid == gid or oid not in L.paths or L.is_final(o) or abnormal(o) or tid not in {str(o["home"].get("id")), str(o["away"].get("id"))}:
                continue
            od = parse_dt(o["date"])
            if od and dt and od > dt and (best is None or (od, oid) < best[0]):
                best = ((od, oid), oid, o)
        if tid and best:
            out.append((t, best[1], best[2]))
    return out


