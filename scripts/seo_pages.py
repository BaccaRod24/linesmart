# ---------------------------------------------------------------- per-league context
class League:
    def __init__(self, lg, ix, props, arch: Archive, now, base_url):
        self.lg, self.now, self.base_url = lg, now, base_url
        self.league = dict(ix.get("league") or {})
        self.kind = self.league.get("kind") or ("mma" if lg == "ufc" else "football")
        self.name = NAMES[lg]
        self.full = self.league.get("full") or self.name
        self.generated = parse_dt(ix.get("generated")) or now
        self.teams = ix.get("teams") or {}
        self.events = {str(e["id"]): e for e in (ix.get("events") or []) if e.get("id")}
        self.props = props or {}
        self.markets = self.props.get("markets") or {}
        self.cur = {str(g["id"]): norm_scores(g) for g in (ix.get("games") or []) if g.get("id") and g.get("home") and g.get("away")}
        self.arch = arch
        self.games = {}      # id -> game used for the page (current copy, or archived copy with closing lines)
        self.current = set() # ids still in the data window (pages hydrate with the live app view)
        self.paths = {}      # id -> path
        self.old_paths = {}  # id -> [older paths to redirect]
        self.players = {}    # pid -> {"p": player, "rows": [(gid, row)], "path": ..., "archived": bool, "seen": iso}
        self.team_paths = {} # team id -> path
        self.team_old = {}   # team id -> [older paths to redirect]
        self.team_info = {}  # team id -> side dict (name/abbr/logo/...)
        self.event_paths = {}
        self.hub = f"{lg}/"

    def is_final(self, g):
        """A finished result. Postponed and canceled games stay up, but they are not finals and have no score."""
        if abnormal(g):
            return False
        return g.get("state") == "post" or bool(g.get("completed"))

    def score_known(self, g):
        if self.lg == "ufc":
            return bool(g.get("result")) or any((g.get(s) or {}).get("winner") for s in ("home", "away"))
        return isnum((g.get("home") or {}).get("score")) and isnum((g.get("away") or {}).get("score"))

    def select(self):
        cfg, now = LEAGUES[self.lg], self.now
        arch_games = (self.arch.games.get(self.lg) or {}) if self.arch.dir else {}
        horizon = now + timedelta(days=cfg["days"])
        for gid, g in self.cur.items():
            dt = parse_dt(g.get("date"))
            if not dt:
                continue
            ar = arch_games.get(gid) or {}
            if abnormal(g):
                # Stay published as Postponed / Canceled. Not hydrated, so the static page keeps that label.
                self.games[gid] = g
                continue
            st = g.get("state")
            if st == "pre":
                if dt > horizon or (cfg["odds"] and not pv.has_line(g)) or dt < now - timedelta(hours=12):
                    continue
                # pro leagues: games without a line yet still get a page when they're close (records, form, injuries)
                if not pv.has_line(g) and dt > now + timedelta(hours=72):
                    continue
                self.games[gid] = g
            elif st == "in":
                self.games[gid] = dict(g, **(ar.get("closing") or {})) if ar.get("closing") and not pv.has_line(g) else g
            else:
                if not self.score_known(g):
                    continue
                gg = dict(g)
                cl = ar.get("closing") if isinstance(ar.get("closing"), dict) else None
                if cl:
                    gg.update(books=cl.get("books") or {}, odds=cl.get("odds"), _closing=True, _closedAt=cl.get("closedAt"))
                    gg["closing"] = cl
                elif pv.has_line(g):
                    gg["_closing"] = True
                if ar.get("move") and not gg.get("move"):
                    gg["move"] = ar["move"]
                self.games[gid] = gg
            self.current.add(gid)
        for gid, rec in arch_games.items():
            rec = norm_scores(rec)
            if gid in self.cur:
                continue
            if abnormal(rec):
                self.games[gid] = dict(rec, _archived=True)
                continue
            if not self.is_final(rec) or not self.score_known(rec):
                continue
            dt = parse_dt(rec.get("date"))
            if not dt:
                continue
            gg = dict(rec)
            cl = rec.get("closing") if isinstance(rec.get("closing"), dict) else None
            gg.update(books=(cl or {}).get("books") or {}, odds=(cl or {}).get("odds"), _closing=bool(cl),
                      _closedAt=(cl or {}).get("closedAt"), _archived=True)
            self.games[gid] = gg

    def assign_paths(self):
        stored = self.arch.state.setdefault("paths", {}).setdefault(self.lg, {}) if self.arch.dir else {}
        used = set()
        # keep paths we already published; new games get one in date order
        order = sorted(self.games.values(), key=lambda g: (g.get("date") or "", str(g["id"])))
        for g in order:
            gid = str(g["id"])
            prev = stored.get(gid) or []
            want = self.game_slug(g)
            if prev and (g.get("state") != "pre" or prev[0].rsplit("/", 2)[-2].startswith(want)):
                path = prev[0]
            else:
                base = want
                path = self._gpath(base)
                if path in used:
                    path = self._gpath(f"{base}-{gid}")
            used.add(path)
            self.paths[gid] = path
            olds = [p for p in prev if p != path]
            if olds:
                self.old_paths[gid] = olds
            if self.arch.dir:
                stored[gid] = [path] + olds[:3]

    def _gpath(self, slug):
        return f"{self.lg}/{'fights' if self.lg == 'ufc' else 'games'}/{slug}/"

    def game_slug(self, g):
        d = day_et(parse_dt(g["date"]))
        a, h = g.get("away") or {}, g.get("home") or {}
        sep = "vs" if self.lg == "ufc" else "at"
        return f"{slugify(a.get('name') or a.get('abbr'))}-{sep}-{slugify(h.get('name') or h.get('abbr'))}-{d}"

    # players (props) ------------------------------------------------------
    def collect_players(self):
        if self.lg == "ufc":
            return
        P = self.props.get("players") or {}
        slugs = self.arch.state.setdefault("slugs", {}).setdefault(self.lg, {}) if self.arch.dir else {}
        for gid, gp in (self.props.get("games") or {}).items():
            gid = str(gid)
            g = self.cur.get(gid)
            if not g or g.get("state") == "post" or gid not in self.paths:
                continue
            for r in gp.get("props") or []:
                pid = str(r[0])
                if pid not in P:
                    continue
                e = self.players.setdefault(pid, {"p": P[pid], "rows": [], "archived": False, "seen": iso(self.now)})
                e["rows"].append((gid, r))
        ap = self.arch.players.setdefault(self.lg, {}) if self.arch.dir else {}
        for pid, e in self.players.items():
            if self.arch.dir:
                ap[pid] = {"p": e["p"], "rows": e["rows"], "seen": e["seen"]}
        cut = self.now - timedelta(days=PLAYER_KEEP_DAYS)
        for pid in list(ap):
            if (parse_dt(ap[pid].get("seen")) or self.now) < cut:
                del ap[pid]
                continue
            if pid not in self.players:
                e = dict(ap[pid], archived=True)
                e["rows"] = [tuple(x) for x in e.get("rows") or []]
                self.players[pid] = e
        used = {}
        for pid in sorted(self.players, key=lambda k: (self.players[k]["archived"], self.players[k]["p"].get("n") or "", k)):
            base = slugs.get(pid) or slugify(self.players[pid]["p"].get("n") or pid)
            if base in used and used[base] != pid:
                base = f"{base}-{slugify(self.players[pid]['p'].get('ta') or pid)}"
                if base in used:
                    base = f"{base}-{pid}"
            used[base] = pid
            if self.arch.dir:
                slugs[pid] = base
            self.players[pid]["path"] = f"{self.lg}/props/{base}/"

    def collect_teams(self):
        """Slugs follow the current team name. team_paths in state.json remembers the previous slug so a rename
        leaves a canonical + meta-refresh stub (GitHub Pages can't send a 301)."""
        used = {}
        stored = self.arch.state.setdefault("team_paths", {}).setdefault(self.lg, {}) if self.arch.dir else {}
        for gid, g in sorted(self.games.items(), key=lambda kv: kv[1].get("date") or "", reverse=True):
            for s in ("home", "away"):
                t = g.get(s) or {}
                tid = str(t.get("id") or "")
                if not tid or tid in self.team_info:
                    continue
                self.team_info[tid] = t
        for tid, t in sorted(self.team_info.items(), key=lambda kv: (kv[1].get("name") or "", kv[0])):
            base = slugify(t.get("name") or t.get("abbr") or tid)
            if base in used:
                base = f"{base}-{tid}"
            used[base] = tid
            path = f"{self.lg}/{'fighters' if self.lg == 'ufc' else 'teams'}/{base}/"
            prev = stored.get(tid) or []
            olds = [p for p in prev if p != path]
            self.team_paths[tid] = path
            if olds:
                self.team_old[tid] = olds[:3]
            if self.arch.dir:
                stored[tid] = [path] + olds[:3]

    def collect_events(self):
        if self.lg != "ufc":
            return
        evs = {}
        for gid, g in self.games.items():
            ev = g.get("event") or {}
            if ev.get("id"):
                e = evs.setdefault(str(ev["id"]), {"id": str(ev["id"]), "name": ev.get("name") or "UFC", "bouts": [], "date": g.get("date")})
                e["bouts"].append(gid)
                full = self.events.get(str(ev["id"])) or {}
                e.update({k: full[k] for k in ("date", "venue", "city", "venueState", "venueCountry", "segments", "broadcasts", "state", "short") if full.get(k)})
                if not full.get("date") and (g.get("date") or "") < (e.get("date") or "9"):
                    e["date"] = g.get("date")
        used = set()
        for eid, e in sorted(evs.items(), key=lambda kv: kv[1].get("date") or ""):
            base = f"{slugify(e['name'])}-{day_et(parse_dt(e['date']))}"
            if base in used:
                base = f"{base}-{eid}"
            used.add(base)
            e["path"] = f"ufc/events/{base}/"
        self.ev = evs

    # helpers ---------------------------------------------------------------
    def team_link(self, t, label=None):
        p = self.team_paths.get(str((t or {}).get("id") or ""))
        lab = label or tname(t)
        return f'<a class="tlink" href="{esc(p)}">{esc(lab)}</a>' if p else esc(lab)

    def matchup(self, g, short=False):
        a, h = g["away"], g["home"]
        if self.lg == "ufc":
            return f"{tname(a)} vs. {tname(h)}"
        n = (lambda t: pv.side_name(t)) if short else tname
        return f"{n(a)} at {n(h)}"

    def lines_brief(self, g):
        """'PHI -6.5 · O/U 54.5' from the reference book."""
        _, b = pv.ref_book(g)
        if not b:
            return ""
        bits = []
        h, a = g["home"], g["away"]
        if self.kind in ("football", "basketball") and isnum(b.get("homeSpread")):
            hs = b["homeSpread"]
