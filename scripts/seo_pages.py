def state_slug(code, name):
    """Full state name, lowercase, hyphenated. DC is /washington-dc/ (not district-of-columbia)."""
    if code == "DC":
        return "washington-dc"
    return slugify(name or "")


def load_books(path=None):
    p = Path(path) if path else BOOKS_PATH
    doc = json.loads(p.read_text())
    if not isinstance(doc, dict) or not isinstance(doc.get("states"), dict) or not doc.get("asOf"):
        raise SystemExit(f"seo_pages: {p} needs states and asOf")
    return doc


def legal_states(doc):
    """(code, state, slug) for onlineLegal entries, by name. Other states have no page yet."""
    rows = []
    for code, st in (doc.get("states") or {}).items():
        if not isinstance(st, dict) or not st.get("onlineLegal"):
            continue
        slug = (st.get("slug") or state_slug(code, st.get("name"))).strip("/")
        rows.append((str(code), st, slug))
    rows.sort(key=lambda r: ((r[1].get("name") or ""), r[0]))
    return rows


def slug_clashes(doc):
    """Slugs that would overwrite a league dir, a tool page, or another state."""
    slugs = [s for _, _, s in legal_states(doc)]
    bad = [s for s in slugs if (not s) or s in RESERVED_DIRS]
    counts = {}
    for s in slugs:
        counts[s] = counts.get(s, 0) + 1
    dupes = [s for s, n in counts.items() if n > 1]
    return sorted(set(bad + dupes))


def books_age_days(doc, today):
    asof = datetime.strptime(doc["asOf"], "%Y-%m-%d").date()
    return (today - asof).days


def require_fresh_books(doc, today=None):
    """Fail the build when asOf is more than 30 days old, so someone re-verifies the list."""
    today = today or datetime.now(timezone.utc).date()
    age = books_age_days(doc, today)
    if age > ASOF_MAX_DAYS:
        raise SystemExit(
            f"seo_pages: data/books-by-state.json asOf {doc['asOf']} is {age} days old "
            f"(limit {ASOF_MAX_DAYS}). Re-verify the state list and update asOf.")
    return age


